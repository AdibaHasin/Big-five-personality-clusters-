def reverse_items(columns, max_scale=5):

    """
    Reverses the Likert scores in the specified columns.

    columns: list of columns to be reversed
    max_scale: Maximum value of the Likert scale
    """

    for col in columns:
        df[col] = (max_scale + 1) - df[col]

def scoreCalculator(group,groupname=""):
    df[f"{groupname}_Score"] = df[group].mean(axis=1)

