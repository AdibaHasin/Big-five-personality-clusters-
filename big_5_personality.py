# single PCA space for all participants
pca = PCA(n_components=2, random_state=42)
Z = pca.fit_transform(df_model)          # df_model = scaled 5 trait columns (no country)
df_pca = pd.DataFrame(Z, columns=["PCA1","PCA2"])
df_pca["Cluster"] = k_fitted             # KMeans labels
df_pca["country"] = scores_df["country"] # attach country

# limit to top N countries and sample to reduce overplotting
topN = 8
top_countries = df_pca["country"].value_counts().head(topN).index
small = (df_pca[df_pca["country"].isin(top_countries)]
         .groupby("country", group_keys=False)
         .apply(lambda g: g.sample(min(len(g), 3000), random_state=42)))  # ≤3k pts per country

# ompute cluster centroids per country to overlay
centroids = (small.groupby(["country","Cluster"])[["PCA1","PCA2"]]
             .mean().reset_index())

# one panel per country
g = sns.relplot(
    data=small, x="PCA1", y="PCA2", hue="Cluster",
    col="country", col_wrap=4, kind="scatter",
    height=3.5, aspect=1, alpha=0.6, s=10, palette="Set2",
    facet_kws=dict(sharex=True, sharey=True)
)
g.set_titles("{col_name}")
g.set_axis_labels("PCA1", "PCA2")
g._legend.set_title("Clusters")

# Overlay centroids as big markers (✕)
for ax, country in zip(g.axes.flat, g.col_names):
    cc = centroids[centroids["country"] == country]
    ax.scatter(cc["PCA1"], cc["PCA2"], s=160, marker="X", linewidths=1.2, edgecolors="black", alpha=0.9)

